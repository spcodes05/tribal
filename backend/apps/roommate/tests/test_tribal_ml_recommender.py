BASE_PROFILE = {
    "gender": "male",
    "budget_min": 11000,
    "budget_max": 16000,
    "sleep_schedule": "night_owl",
    "wake_time": "08:30",
    "smoking": "non_smoker",
    "drinking": "social",
    "cleanliness": 4,
    "noise_level": 2,
    "guests_preference": "sometimes",
    "food_preference": "vegetarian",
    "pets": "okay_with_pets",
    "study_habit": "quiet",
    "interests": ["Hiking", "Music"],
    # present in real service.py dicts, must be ignored by ML:
    "gender_preference": "any",
    "room_type_preference": "any",
}


def make_profile(**overrides):
    p = copy.deepcopy(BASE_PROFILE)
    p.update(overrides)
    return p


