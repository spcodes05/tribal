# ─────────────────────────────────────────────────────────────────────
# 5. Domain weighting actually present in the transformed vector
# ─────────────────────────────────────────────────────────────────────

def test_domain_weights_are_applied_in_transformed_vector():
    """Same profile except gender flips -> the change should land only in
    the gender domain's column slice, and the magnitude of that change
    should reflect the gender domain weight (5.0), not an arbitrary
    scale."""
    a = make_profile(gender="male")
    b = make_profile(gender="female")
    va = rec.transform_user(a)[0]
    vb = rec.transform_user(b)[0]

    domain_slices = rec._PREPROCESSOR["domain_slices"]
    diff = va - vb

    for domain, (lo, hi) in domain_slices.items():
        segment_diff = diff[lo:hi]
        if domain == "gender":
            assert np.any(np.abs(segment_diff) > 1e-9), "gender segment should differ"
        else:
            assert np.allclose(segment_diff, 0.0), f"{domain} segment should NOT differ"

    # gender is the highest-weighted domain (5.0) -- confirm it's recorded
    # as such in the artifact actually driving inference.
    assert rec._DOMAIN_WEIGHTS["gender"] == 5.0
    assert rec._DOMAIN_WEIGHTS["gender"] == max(rec._DOMAIN_WEIGHTS.values())


def test_gender_mismatch_costs_more_than_five_domain_lifestyle_mismatch():
    """Documents the deliberate, disclosed design property: a single
    gender mismatch reduces compatibility more than simultaneously
    mismatching sleep_schedule, smoking, food_preference, study_habit,
    and pets."""
    a = make_profile()
    gender_mismatch = make_profile(gender="female")
    lifestyle_mismatch = make_profile(
        sleep_schedule="early_bird", smoking="smoker",
        food_preference="non_vegetarian", study_habit="group_study",
        pets="not_okay_with_pets",
    )
    r_gender = rec.pairwise_compatibility(a, gender_mismatch)
    r_lifestyle = rec.pairwise_compatibility(a, lifestyle_mismatch)
    assert r_gender["compatibility_score"] < r_lifestyle["compatibility_score"]


