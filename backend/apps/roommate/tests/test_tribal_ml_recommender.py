def test_artifact_version_mismatch_raises_clear_error(tmp_path, monkeypatch):
    """Simulates a stale preprocessor (wrong feature_space_version)
    paired with the current model -- must fail loudly at load time."""
    with open(_ML_DIR / "tribal_preprocessor.pkl", "rb") as f:
        preprocessor = pickle.load(f)
    stale_preprocessor = dict(preprocessor)
    stale_preprocessor["feature_space_version"] = "some_old_version"

    stale_dir = tmp_path / "stale_artifacts"
    stale_dir.mkdir()
    shutil.copy(_ML_DIR / "tribal_kmeans_model.pkl", stale_dir / "tribal_kmeans_model.pkl")
    shutil.copy(_ML_DIR / "tribal_cluster_data.pkl", stale_dir / "tribal_cluster_data.pkl")
    with open(stale_dir / "tribal_preprocessor.pkl", "wb") as f:
        pickle.dump(stale_preprocessor, f)

    import importlib
    monkeypatch.setattr(rec, "_ARTIFACT_DIR", stale_dir, raising=False)
    monkeypatch.setattr(rec, "_MODEL_PATH", stale_dir / "tribal_kmeans_model.pkl", raising=False)
    monkeypatch.setattr(rec, "_PREPROCESSOR_PATH", stale_dir / "tribal_preprocessor.pkl", raising=False)
    monkeypatch.setattr(rec, "_CLUSTER_DATA_PATH", stale_dir / "tribal_cluster_data.pkl", raising=False)

    with pytest.raises(rec.TribalRecommenderError, match="feature_space_version"):
        rec._load_artifacts()


