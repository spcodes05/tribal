# ─────────────────────────────────────────────────────────────────────
# 11. CRITICAL: train-vs-inference consistency check
# ─────────────────────────────────────────────────────────────────────

@pytest.mark.skipif(not _DATASET_PATH.exists(), reason="dataset.csv not available")
def test_train_vs_inference_produces_identical_vector_for_a_training_row():
    """Takes a real row from the training data, runs it through the
    LIVE inference _transform(), and asserts it exactly reproduces the
    corresponding row of the feature matrix that was actually clustered
    during training (persisted in tribal_cluster_data.pkl)."""
    with open(_ML_DIR / "tribal_cluster_data.pkl", "rb") as f:
        cluster_data = pickle.load(f)
    training_matrix = cluster_data["feature_matrix"]
    training_user_ids = list(cluster_data["user_ids"])

    df = pd.read_csv(_DATASET_PATH)

    for row_idx in (0, 1, 5000, 9999):
        row = df.iloc[row_idx]
        assert int(row["user_id"]) == training_user_ids[row_idx]

        user_data = {
            "gender": row["gender"],
            "budget_min": row["budget_min"],
            "budget_max": row["budget_max"],
            "sleep_schedule": row["sleep_schedule"],
            "wake_time": row["wake_time"],
            "smoking": row["smoking"],
            "drinking": row["drinking"],
            "cleanliness": row["cleanliness"],
            "noise_level": row["noise_level"],
            "guests_preference": row["guests_preference"],
            "food_preference": row["food_preference"],
            "pets": row["pets"],
            "study_habit": row["study_habit"],
            "interests": row["interests"],
        }
        inference_vector = rec.transform_user(user_data)[0]
        training_vector = training_matrix[row_idx]

        assert np.allclose(inference_vector, training_vector, atol=1e-8), (
            f"Row {row_idx}: inference transform does not match the "
            "vector actually used to train the model."
        )


